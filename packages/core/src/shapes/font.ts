/**
 * A single-stroke technical font.
 *
 * Three.js ships no font data, so extruded outline text would mean bundling a
 * typeface. A stroke font suits this app better anyway: each glyph is a set of
 * polylines, which sweep into tubes exactly like a drawn stroke, so text
 * inherits the brush, the booleans, the move tool and the export path without
 * a second rendering approach.
 *
 * Coordinates sit in an em box: baseline at y = 0, cap height at y = 1, glyphs
 * 0.55 wide. Lowercase sits at an x-height of 0.62 with descenders to -0.28,
 * which is what makes it read as lowercase rather than as small capitals.
 */

